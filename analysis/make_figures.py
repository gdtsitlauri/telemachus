#!/usr/bin/env python3
"""Figures and result tables for TELEMACHUS, built only from results/.

Usage (from the TELEMACHUS folder):  python analysis/make_figures.py
Writes figures/*.png, figures/*.pdf and tables/RESULTS.md.
"""
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
R, F, T = ROOT / "results", ROOT / "figures", ROOT / "tables"
F.mkdir(exist_ok=True); T.mkdir(exist_ok=True)
plt.rcParams.update({"font.size": 9, "axes.spines.top": False, "axes.spines.right": False, "figure.dpi": 150})
COL = {"telemachus": "C0", "learned": "C0", "online": "C0", "confidence": "C3", "confidence_gate": "C3", "static": "C3",
       "no_expert": "C9", "no_learning": "C1", "budget_voi": "C2", "conservative": "C7", "entropy": "C3",
       "margin": "C1", "random": "C7", "agreement": "C2", "oracle": "k"}
md = ["# TELEMACHUS: result tables", "", "Generated by `analysis/make_figures.py` from `results/`. Do not edit by hand.", ""]


def load(p):
    return json.loads((R / p).read_text())


def save(fig, name):
    fig.tight_layout()
    for ext in ("png", "pdf"):
        fig.savefig(F / f"{name}.{ext}", bbox_inches="tight")
    plt.close(fig)


# 1. Certified navigation -----------------------------------------------------
v6 = load("1_navigation_certified/v6_report.json")
alpha_nav = load("1_navigation_certified/main/calibration_certificate.json")["alpha"]
fig, axes = plt.subplots(1, 2, figsize=(7.2, 2.8), sharey=True)
md += ["## 1. Certified navigation (alpha = %.2f, delta = 0.10, 480 test episodes per method)" % alpha_nav, "",
       "| split | method | certified margin | collision | 95% CI | success | deferred | cost |", "|---|---|---|---|---|---|---|---|"]
for ax, split, title in ((axes[0], "main", "test (exchangeable)"), (axes[1], "main_stress", "stress (outside assumption)")):
    for m, v in v6[split].items():
        lo, hi = v["collision_ci95"]
        ax.errorbar(v["cost_mean"], v["collision_rate"], yerr=[[v["collision_rate"] - lo], [hi - v["collision_rate"]]],
                    fmt="o", color=COL.get(m, "k"), capsize=2, label=m)
        md.append(f"| {split} | {m} | {v['setting']['safety_margin']} | {v['collision_rate']:.3f} | [{lo:.3f}, {hi:.3f}] | "
                  f"{v['success']:.3f} | {v['deferred']:.3f} | {v['cost_mean']:.1f} |")
    ax.axhline(alpha_nav, ls="--", c="grey", lw=1); ax.text(ax.get_xlim()[1], alpha_nav, "alpha ", va="bottom", ha="right", color="grey")
    ax.set_title(title); ax.set_xlabel("mean resource cost per episode")
axes[0].set_ylabel("collision rate"); axes[1].legend(fontsize=7, frameon=False)
save(fig, "fig1_navigation_certified")
md += ["", "Budget study (max cost 40):", "", "| method | margin | collision | success | deferred | cost |", "|---|---|---|---|---|---|"]
for m, v in v6["budget"].items():
    md.append(f"| {m} | {v['setting']['safety_margin']} | {v['collision_rate']:.3f} | {v['success']:.3f} | {v['deferred']:.3f} | {v['cost_mean']:.1f} |")

# 2. Navigation under shift: online margin ------------------------------------
om = load("2_navigation_online_shift/final.json")
proto = om["protocol"]; a2 = proto["alpha"]
streams = [k for k in om if k.startswith("stream")]
fig, axes = plt.subplots(1, 2, figsize=(7.2, 2.8))
md += ["", "## 2. Navigation under deployment shift: online safety margin (alpha = %.2f)" % a2, "",
       "| method | collision (all) | collision (2nd half) | success | deferred | cost | episodes |", "|---|---|---|---|---|---|---|"]
for m in ("static", "online", "conservative"):
    cum = []
    for s in streams:
        tr = om[s][m]["trace"]
        c = np.cumsum([t["collision"] * t["n"] for t in tr]) / np.cumsum([t["n"] for t in tr])
        cum.append(c)
        axes[0].plot([t["margin"] for t in tr], color=COL[m], alpha=.6, lw=1, label=m if s == streams[0] else None)
    axes[1].plot(np.mean(cum, 0), color=COL[m], label=m)
    S = [om[s][m]["summary"] for s in streams]; H = [om[s][m]["second_half"] for s in streams]
    n = sum(x["n"] for x in S)
    md.append(f"| {m} | {np.mean([x['collision'] for x in S]):.3f} | {np.mean([x['collision'] for x in H]):.3f} | "
              f"{np.mean([x['success'] for x in S]):.3f} | {np.mean([x['deferred'] for x in S]):.3f} | {np.mean([x['cost'] for x in S]):.1f} | {n} |")
hp = load("2_navigation_online_shift/final_hp.json")
hcum = []
for st in hp["streams"]:
    col = np.array([e["collision"] for e in st["episodes"]])
    hcum.append((np.cumsum(col) / np.arange(1, len(col) + 1))[11::12])
    axes[0].plot([e["s"] for e in st["episodes"]][::12], color="C4", alpha=.6, lw=1,
                 label="guaranteed (Thm A)" if st is hp["streams"][0] else None)
axes[1].plot(np.mean(hcum, 0), color="C4", label="guaranteed (Thm A)")
axes[0].axhline(hp["protocol"]["s_f"], ls=":", c="C4", lw=.8)
axes[0].set_xlabel("chunk (12 episodes)"); axes[0].set_ylabel("safety margin / control s (m)"); axes[0].legend(frameon=False, fontsize=7)
axes[1].axhline(a2, ls="--", c="grey", lw=1); axes[1].set_xlabel("chunk"); axes[1].set_ylabel("cumulative collision rate")
axes[1].set_title("mean of %d independent streams" % len(streams)); axes[1].legend(frameon=False, fontsize=7)
save(fig, "fig2_navigation_online_shift")
md += ["", "Guaranteed online control with human-handover fallback (Theorem A; update after every episode; "
       f"eta = {hp['protocol']['eta']}, alpha* = {hp['streams'][0]['alpha_star']:.4f}, theorem bound "
       f"{hp['streams'][0]['theorem_bound']:.4f}):", "",
       "| stream | collision | <= theorem bound | success | deferred (incl. handover) | handover | cost | episodes |",
       "|---|---|---|---|---|---|---|---|"]
for st in hp["streams"]:
    md.append(f"| {st['base']} | {st['collision']:.3f} | {st['collision'] <= st['theorem_bound']} | {st['success']:.3f} | "
              f"{st['deferred']:.3f} | {st['handover']:.3f} | {st['cost']:.1f} | {st['n']} |")

